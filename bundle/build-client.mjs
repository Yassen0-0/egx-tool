// Builds client.js, the file the host loads, from the ES modules in src/ (entry: src/index.js).
//   - esbuild bundles the modules into one IIFE; 'react' stays external and resolves to the host's
//     React through the module loader's require(); .css files are imported as text.
//   - the vendored Lightweight Charts standalone build is evaluated inside the factory, where it
//     would assign window.LightweightCharts: the wrapper captures it into a factory-local constant
//     (__EGX_LIGHTWEIGHT_CHARTS__, read by src/runtime.js) and restores the global, so nothing
//     leaks and the library only runs when the factory materializes.
// Usage: node bundle/build-client.mjs [--check]   (--check: fail when client.js is out of date)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const read = (...p) => readFileSync(join(here, ...p), 'utf8')

const result = await build({
  entryPoints: [join(here, 'src', 'index.js')],
  bundle: true,
  format: 'iife',
  globalName: '__egx',
  external: ['react'],
  loader: { '.css': 'text' },
  target: 'es2020',
  charset: 'utf8',
  legalComments: 'none',
  write: false,
  logLevel: 'silent',
})
const bundled = result.outputFiles[0].text
const library = read('vendor', 'lightweight-charts.standalone.production.js')

const output = `// GENERATED by build-client.mjs from src/ (esbuild). Edit the sources, then rebuild.
// Source of the EGX panels for the Monos desktop app: sidebar entries plus pages in the main area.
window.__ModuleLoader__.load({
  id: 'dsh-egx-bundle',
  factory(require) {
    const __EGX_LIGHTWEIGHT_CHARTS__ = (() => {
      const previous = Object.getOwnPropertyDescriptor(window, 'LightweightCharts')
${library}
      const lib = window.LightweightCharts
      if (previous) Object.defineProperty(window, 'LightweightCharts', previous)
      else delete window.LightweightCharts
      return lib
    })()
${bundled}
    return __egx.default
  },
})
`
const target = join(here, 'client.js')
if (process.argv.includes('--check')) {
  if (read('client.js') !== output) {
    console.error('client.js is out of date: run node bundle/build-client.mjs and commit it')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  writeFileSync(target, output)
  console.log(`client.js written (${Math.round(output.length / 1024)} KB)`)
}
