// Builds client.js: src/client.src.js with the vendored Lightweight Charts
// standalone build inlined. The library assigns window.LightweightCharts; the
// wrapper captures it into a module-local constant and restores the global, so
// nothing leaks and the code only runs when the client factory materializes.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(join(here, 'src', 'client.src.js'), 'utf8')
const library = readFileSync(join(here, 'vendor', 'lightweight-charts.standalone.production.js'), 'utf8')
const marker = '/* @inline lightweight-charts */'
if (!source.includes(marker)) throw new Error(`marker ${marker} not found in src/client.src.js`)

const inlined = `const LightweightCharts = (() => {
      const previous = Object.getOwnPropertyDescriptor(window, 'LightweightCharts')
${library}
      const lib = window.LightweightCharts
      if (previous) Object.defineProperty(window, 'LightweightCharts', previous)
      else delete window.LightweightCharts
      return lib
    })()`

const banner = '// GENERATED by build-client.mjs from src/client.src.js. Edit the source, then rebuild.\n'
writeFileSync(join(here, 'client.js'), banner + source.replace(marker, () => inlined))
console.log(`client.js written (${Math.round((banner.length + source.length + library.length) / 1024)} KB)`)
