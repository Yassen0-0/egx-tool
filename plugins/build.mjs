// Builds client.js for every Monos plugin that has a screen (plugins/<name>/src/index.js).
//   - esbuild bundles the plugin's modules and the shared/ ones it imports into one IIFE; 'react'
//     stays external and resolves to the host's React through the module loader's require();
//     .css files are imported as text.
//   - the host loads each client.js as a lazy factory whose id must equal the package name.
//   - a plugin with "monos": { "charts": true } gets the vendored Lightweight Charts build,
//     evaluated inside its factory: the wrapper captures window.LightweightCharts into
//     __EGX_LIGHTWEIGHT_CHARTS__ (read by shared/charts.js) and restores the global.
// Usage: node plugins/build.mjs [--check] [name…]   (--check: fail when a client.js is out of date)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const check = args.includes('--check')
const only = args.filter((a) => !a.startsWith('--'))

/** Every plugin folder: plugins/monos-* with a package.json (order = folder name). */
export function plugins() {
  return readdirSync(here).filter((d) => d.startsWith('monos-') && existsSync(join(here, d, 'package.json'))).sort()
    .map((dir) => ({ dir: join(here, dir), manifest: JSON.parse(readFileSync(join(here, dir, 'package.json'), 'utf8')) }))
}

async function clientFor({ dir, manifest }) {
  const result = await build({
    entryPoints: [join(dir, 'src', 'index.js')],
    bundle: true, format: 'iife', globalName: '__monos', external: ['react'],
    loader: { '.css': 'text' }, target: 'es2020', charset: 'utf8', legalComments: 'none',
    write: false, logLevel: 'silent',
  })
  const charts = manifest.monos && manifest.monos.charts
    ? `    const __EGX_LIGHTWEIGHT_CHARTS__ = (() => {
      const previous = Object.getOwnPropertyDescriptor(window, 'LightweightCharts')
${readFileSync(join(dir, 'vendor', 'lightweight-charts.standalone.production.js'), 'utf8')}
      const lib = window.LightweightCharts
      if (previous) Object.defineProperty(window, 'LightweightCharts', previous)
      else delete window.LightweightCharts
      return lib
    })()
` : ''
  return `// GENERATED by plugins/build.mjs from ${manifest.name}/src and plugins/shared (esbuild). Edit the sources, then rebuild.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
${charts}${result.outputFiles[0].text}
    return __monos.default
  },
})
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  let stale = 0
  for (const plugin of plugins()) {
    if (!existsSync(join(plugin.dir, 'src', 'index.js'))) continue
    if (only.length && !only.includes(plugin.manifest.name)) continue
    const output = await clientFor(plugin)
    const target = join(plugin.dir, 'client.js')
    if (check) {
      const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
      if (current !== output) { console.error(`${plugin.manifest.name}: client.js is out of date`); stale++ }
    } else {
      writeFileSync(target, output)
      console.log(`${plugin.manifest.name}: client.js written (${Math.round(output.length / 1024)} KB)`)
    }
  }
  if (check && stale) { console.error('run: npm run build'); process.exit(1) }
  if (check) console.log('every client.js is up to date')
}
